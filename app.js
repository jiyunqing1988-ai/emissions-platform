function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

// The workbook stores the version as a bare stamp ("20260726"), which reads as a
// serial number rather than the date it is. Display only — the data file is
// generated by scripts/extract_workbook.py and stays as-is.
function formatVersion(value) {
  const stamp = String(value ?? "");
  return /^\d{8}$/.test(stamp) ? `${stamp.slice(0, 4)}.${stamp.slice(4, 6)}.${stamp.slice(6)}` : stamp;
}

function formatValue(value) {
  if (value === "" || value === null || value === undefined) return "";
  if (typeof value !== "number") return String(value);
  // "系统设置 → 数值显示精度" only rounds the display; the underlying data is untouched.
  const decimals = { d4: 4, d2: 2 }[state.settings?.precision];
  const text = Number.isInteger(value)
    ? String(value)
    : decimals === undefined
      ? Number(value.toPrecision(8)).toString()
      : String(Number(value.toFixed(decimals)));
  // Grouping has to run for integers too — that is exactly where it earns its keep.
  if (!state.settings?.grouping) return text;
  const [whole, fraction] = text.split(".");
  const grouped = whole.replace(/\B(?=(\d{3})+(?!\d))/g, ",");
  return fraction ? `${grouped}.${fraction}` : grouped;
}

function formatFormula(value) {
  return String(value ?? "")
    .replace(/\bF\d+\b/g, "CO2")
    .replace(/\bG\d+\b/g, "CH4")
    .replace(/\bH\d+\b/g, "N2O")
    .replaceAll("*", " × ")
    .replaceAll("+", " + ")
    .replaceAll("/", " / ")
    .replace(/\s+/g, " ")
    .replace(/^= /, "=")
    .trim();
}

