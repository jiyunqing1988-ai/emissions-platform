function renderCleanRows(rows) {
  return `
    <div class="clean-content">
      ${rows
        .map((row) => row.cells.filter((cell) => cell !== ""))
        .filter((cells) => cells.length)
        .map((cells) => {
          if (cells.length === 1) {
            return `<p>${escapeHtml(formatValue(cells[0]))}</p>`;
          }
          return `
            <div class="clean-row">
              ${cells.map((cell) => `<span>${escapeHtml(formatValue(cell))}</span>`).join("")}
            </div>
          `;
        })
        .join("")}
    </div>
  `;
}

