// CSS scroll-snap plus scroll-snap-stop:always already gives touch one field per
// flick. Wheel and trackpad deltas bypass that model — a single large delta lands
// mid-document — so those are paged explicitly here, one field per gesture.
let homePagerCleanup = null;

// Handheld hides the header, desktop keeps it sticky over the fields. Measured
// rather than hardcoded so the two layouts share one pager.
function headerOffset() {
  const header = document.querySelector(".site-header");
  if (!header || getComputedStyle(header).display === "none") return 0;
  return Math.round(header.getBoundingClientRect().height);
}

function teardownHomePager() {
  if (homePagerCleanup) {
    homePagerCleanup();
    homePagerCleanup = null;
  }
}

function setupHomePager() {
  teardownHomePager();
  const sections = [...els.homeView.querySelectorAll(".home-page > section")];
  if (sections.length < 2) return;

  const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  let locked = false;

  // Which field is at the top right now. Derived from the sections' own offsets
  // rather than scrollY / innerHeight: on desktop a sticky 80px header makes a
  // field shorter than the viewport, so the arithmetic version drifts a page.
  const currentIndex = () => {
    const line = window.scrollY + headerOffset() + 2;
    let index = 0;
    sections.forEach((section, i) => {
      if (section.offsetTop <= line) index = i;
    });
    return index;
  };

  const goto = (direction) => {
    if (locked) return;
    const current = currentIndex();
    const next = Math.min(sections.length - 1, Math.max(0, current + direction));
    if (next === current) return;
    locked = true;
    window.scrollTo({ top: sections[next].offsetTop - headerOffset(), behavior: reduced ? "auto" : "smooth" });
    // Long enough to outlast the smooth scroll and any trailing momentum deltas.
    window.setTimeout(() => {
      locked = false;
    }, reduced ? 60 : 700);
  };

  // Accumulate until the gesture is unmistakably deliberate; a light trackpad
  // graze emits deltas of 1-5 and must not turn a page on its own. The buffer
  // decays between gestures so two nudges do not add up into a flip.
  const THRESHOLD = 60;
  let accumulated = 0;
  let decay = null;

  const onWheel = (event) => {
    if (Math.abs(event.deltaY) <= Math.abs(event.deltaX)) return;
    event.preventDefault();
    if (locked) return;
    accumulated += event.deltaY;
    window.clearTimeout(decay);
    decay = window.setTimeout(() => {
      accumulated = 0;
    }, 180);
    if (Math.abs(accumulated) < THRESHOLD) return;
    const direction = accumulated > 0 ? 1 : -1;
    accumulated = 0;
    goto(direction);
  };

  window.addEventListener("wheel", onWheel, { passive: false });
  homePagerCleanup = () => {
    window.clearTimeout(decay);
    window.removeEventListener("wheel", onWheel);
  };
}

