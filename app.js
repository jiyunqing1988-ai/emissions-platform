// sourceTypeCounts() plus the factors that carry no 数据来源 at all, so the rule
// accounts for all 626 rather than silently dropping the unlabelled ones.
function sourceRule() {
  const labelled = sourceTypeCounts();
  const total = state.data.metadata.totalFactors;
  const counted = labelled.reduce((sum, item) => sum + item.count, 0);
  const rows = labelled.map(({ label, count }) => ({ label, count }));
  if (counted < total) rows.push({ label: "未标注", count: total - counted, blank: true });
  const max = rows.length ? Math.max(...rows.map((r) => r.count)) : 1;
  return { rows: rows.map((r) => ({ ...r, w: Math.round((r.count / max) * 1000) / 10 })), counted, total };
}

