let accountPopCleanup = null;

function closeAccountPop({ focusButton = false } = {}) {
  if (!accountPopCleanup) return;
  accountPopCleanup();
  accountPopCleanup = null;
  els.accountPop.classList.add("hidden");
  els.accountButton.setAttribute("aria-expanded", "false");
  if (focusButton) els.accountButton.focus();
}

function openAccountPop() {
  els.accountPop.innerHTML = renderAccountPop();
  els.accountPop.classList.remove("hidden");
  els.accountButton.setAttribute("aria-expanded", "true");

  const items = () => [...els.accountPop.querySelectorAll("[role='menuitem']")];
  items()[0]?.focus();

  // A click that opened the menu must not immediately close it, so the outside
  // listener goes on at the end of this task rather than during the same event.
  const onPointerDown = (event) => {
    if (!els.accountPop.contains(event.target) && !els.accountButton.contains(event.target)) closeAccountPop();
  };
  const onKeyDown = (event) => {
    if (event.key === "Escape") {
      closeAccountPop({ focusButton: true });
      return;
    }
    if (event.key !== "ArrowDown" && event.key !== "ArrowUp") return;
    const list = items();
    if (!list.length) return;
    event.preventDefault();
    const at = list.indexOf(document.activeElement);
    const step = event.key === "ArrowDown" ? 1 : -1;
    list[(at + step + list.length) % list.length].focus();
  };
  const onFocusOut = () => {
    window.setTimeout(() => {
      if (!accountPopCleanup) return;
      const inside = els.accountPop.contains(document.activeElement) || els.accountButton.contains(document.activeElement);
      if (!inside) closeAccountPop();
    }, 0);
  };

  window.setTimeout(() => document.addEventListener("pointerdown", onPointerDown), 0);
  els.accountPop.addEventListener("keydown", onKeyDown);
  els.accountPop.addEventListener("focusout", onFocusOut);
  window.addEventListener("resize", closeAccountPop);
  accountPopCleanup = () => {
    document.removeEventListener("pointerdown", onPointerDown);
    els.accountPop.removeEventListener("keydown", onKeyDown);
    els.accountPop.removeEventListener("focusout", onFocusOut);
    window.removeEventListener("resize", closeAccountPop);
  };
}

