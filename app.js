function bindEvents() {
  els.homeLink.addEventListener("click", (event) => {
    event.preventDefault();
    showHomeView();
  });
  els.homeView.addEventListener("click", (event) => {
    const pageButton = event.target.closest("button[data-page]");
    if (pageButton) {
      showContentPage(pageButton.dataset.page);
      return;
    }
    const scopeButton = event.target.closest("button[data-scope]");
    const enterButton = event.target.closest(".enter-library");
    if (!scopeButton && !enterButton) return;
    // A scope bar click is an explicit choice; a plain "enter" honours 系统设置.
    state.scope = scopeButton ? scopeButton.dataset.scope : state.settings.defaultScope;
    state.category = scopeButton ? scopeButton.dataset.category : "全部";
    state.scope1Unit = null;
    state.favoritesOnly = false;
    state.query = "";
    els.searchInput.value = "";
    resetPaging();
    showDataView();
  });
  const runSearch = () => {
    if (state.query === els.searchInput.value) return;
    state.query = els.searchInput.value;
    resetPaging();
    showDataView();
  };
  els.searchButton.addEventListener("click", runSearch);
  // The "search" event covers Enter and the field's native clear (×).
  els.searchInput.addEventListener("search", runSearch);
  els.searchInput.addEventListener("keydown", (event) => {
    if (event.key === "Enter") {
      event.preventDefault();
      runSearch();
    }
  });
  const applyScope = (button) => {
    state.scope = button.dataset.scope;
    state.category = button.dataset.category;
    state.favoritesOnly = false;
    resetPaging();
    showDataView();
  };
  els.scopeNav.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-scope]");
    if (button) applyScope(button);
  });
  els.scopeSwitch.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-scope]");
    if (button) applyScope(button);
  });
  els.categoryStrip.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-category]");
    if (button) applyScope(button);
  });

  els.activeFilters.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-clear]");
    if (!button) return;
    if (button.dataset.clear === "category") state.category = "全部";
    if (button.dataset.clear === "query") {
      state.query = "";
      els.searchInput.value = "";
    }
    resetPaging();
    showDataView();
  });

  els.loadMoreButton.addEventListener("click", () => {
    state.visibleCount += pageSize();
    renderTable();
  });
  // Auto-extend as the sentinel nears the viewport; the button stays as a fallback.
  new IntersectionObserver((entries) => {
    if (entries.some((e) => e.isIntersecting) && !els.loadMore.classList.contains("hidden")) {
      state.visibleCount += pageSize();
      renderTable();
    }
  }, { rootMargin: "600px" }).observe(els.loadMore);
  els.scope1UnitControl.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-unit]");
    if (!button) return;
    state.scope1Unit = button.dataset.unit;
    renderTable();
  });
  els.headerNav.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-page]");
    if (!button) return;
    // 因子库 is the data view, not a doc page; everything else is showContentPage.
    if (button.dataset.page === "data") showDataView();
    else showContentPage(button.dataset.page);
  });
  els.accountButton.addEventListener("click", () => {
    if (accountPopCleanup) closeAccountPop({ focusButton: true });
    else openAccountPop();
  });
  els.accountPop.addEventListener("click", (event) => {
    const button = event.target.closest("[data-action]");
    if (!button) return;
    closeAccountPop();
    handleAccountAction(button.dataset.action);
  });
  els.factorTable.addEventListener("click", (event) => {
    const action = event.target.closest("button[data-action]");
    if (action) {
      const record = state.data.factors.find((item) => item.id === action.dataset.id);
      if (!record) return;
      if (action.dataset.action === "detail") {
        showDetail(record);
        return;
      }
      if (!isLoggedIn()) {
        openAuthDialog("login");
        return;
      }
      toggleFavorite(record.id);
      renderTable();
      return;
    }
    const row = event.target.closest("tr[data-id]");
    if (!row) return;
    const record = state.data.factors.find((item) => item.id === row.dataset.id);
    if (record) showDetail(record);
  });
  els.closeDialog.addEventListener("click", () => els.dialog.close());
  els.closeAuthDialog.addEventListener("click", () => els.authDialog.close());
  els.authForm.addEventListener("submit", handleAuthSubmit);
  els.authSwitchButton.addEventListener("click", () =>
    openAuthDialog(authMode === "register" ? "login" : "register"),
  );

  els.tabBar.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-tab]");
    if (!button) return;
    const tab = button.dataset.tab;
    if (tab === "home") return showHomeView();
    if (tab === "data") {
      state.favoritesOnly = false;
      resetPaging();
      return showDataView();
    }
    if (tab === "qa") return showContentPage("Q&A");
    return showAccountPage("me");
  });

  // Favourite toggle lives inside the detail sheet, which is re-rendered per record.
  els.detailBody.addEventListener("click", (event) => {
    const button = event.target.closest("#favoriteToggle");
    if (!button) return;
    if (!isLoggedIn()) {
      els.dialog.close();
      openAuthDialog("login");
      return;
    }
    const saved = toggleFavorite(button.dataset.id);
    button.classList.toggle("saved", saved);
    button.setAttribute("aria-pressed", String(saved));
    button.textContent = saved ? "★ 已收藏" : "☆ 收藏此因子";
    // Keep the row's star (and the favourites view) in sync with the sheet.
    if (state.activePage === "data") renderTable();
  });

  els.contentPage.addEventListener("click", (event) => {
    const qaScope = event.target.closest("button[data-qa-scope]");
    if (qaScope) {
      state.qaScope = qaScope.dataset.qaScope;
      renderContentPage("Q&A");
      return;
    }
    const accountAction = event.target.closest("button[data-action]");
    if (accountAction) {
      handleAccountAction(accountAction.dataset.action);
      return;
    }
    const button = event.target.closest("button[data-setting]");
    if (!button) return;
    const { setting, value } = button.dataset;
    const parsed = value === "true" ? true : value === "false" ? false : /^\d+$/.test(value) ? Number(value) : value;
    saveSettings({ [setting]: parsed });
    applySettings();
    showAccountPage("settings");
  });
}

// Settings that change presentation rather than data are applied at the document level.
function applySettings() {
  document.body.classList.toggle("hide-notes", state.settings.showNotes === false);
  resetPaging();
}

async function init() {
  state.settings = storedSettings();
  applySettings();
  const response = await fetch("./data/platform-data.json");
  state.data = await response.json();
  showHomeView();
  updateAuthUi();
  bindEvents();
}

init().catch((error) => {
  document.body.innerHTML = `<main class="view-panel"><h1>数据加载失败</h1><pre>${escapeHtml(error.message)}</pre></main>`;
});
